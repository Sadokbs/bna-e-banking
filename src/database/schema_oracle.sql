-- 1. TABLE DES UTILISATEURS
CREATE TABLE BNA_UTILISATEURS (
    ID VARCHAR2(64) NOT NULL,
    IDENTIFIANT VARCHAR2(50) NOT NULL,
    ROLE VARCHAR2(30) NOT NULL,
    NOM_COMPLET VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    TELEPHONE VARCHAR2(30) NOT NULL,
    CIN VARCHAR2(20),
    TITRE VARCHAR2(100),
    ORGANISATION VARCHAR2(200),
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    SALT VARCHAR2(64) NOT NULL,
    ALGO_CHIFFREMENT VARCHAR2(50) DEFAULT 'PBKDF2-SHA256 (10000)',
    STATUT VARCHAR2(20) DEFAULT 'ACTIF',
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_LOGIN_AT TIMESTAMP,
    CONSTRAINT PK_UTILISATEURS PRIMARY KEY (ID),
    CONSTRAINT UQ_UTILISATEURS_IDENTIFIANT UNIQUE (IDENTIFIANT),
    CONSTRAINT CK_UTILISATEURS_ROLE CHECK (ROLE IN ('SUPER_ADMIN', 'ADMIN', 'CLIENT_PARTICULIER', 'CLIENT_PROFESSIONNEL')),
    CONSTRAINT CK_UTILISATEURS_STATUT CHECK (STATUT IN ('ACTIF', 'SUSPENDU', 'EN_ATTENTE'))
);

CREATE INDEX IDX_BNA_USER_IDENTIFIANT ON BNA_UTILISATEURS (IDENTIFIANT);
CREATE INDEX IDX_BNA_USER_ROLE ON BNA_UTILISATEURS (ROLE);
CREATE INDEX IDX_BNA_USER_CIN ON BNA_UTILISATEURS (CIN);

-- 2. TABLE DES COMPTES BANCAIRES
CREATE TABLE BNA_COMPTES (
    ID VARCHAR2(64) NOT NULL,
    USER_ID VARCHAR2(64) NOT NULL,
    NUMERO_COMPTE VARCHAR2(34) NOT NULL,
    TYPE_COMPTE VARCHAR2(50) NOT NULL,
    SOLDE NUMBER(15, 3) DEFAULT 0.000 NOT NULL,
    DEVISE VARCHAR2(5) DEFAULT 'TND' NOT NULL,
    STATUT VARCHAR2(20) DEFAULT 'OUVERT',
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_COMPTES PRIMARY KEY (ID),
    CONSTRAINT UQ_COMPTE_NUMERO UNIQUE (NUMERO_COMPTE),
    CONSTRAINT FK_COMPTE_USER FOREIGN KEY (USER_ID) REFERENCES BNA_UTILISATEURS(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_BNA_COMPTE_USER ON BNA_COMPTES (USER_ID);

-- 3. TABLE DES TRANSACTIONS & VIREMENTS
CREATE TABLE BNA_TRANSACTIONS (
    ID VARCHAR2(64) NOT NULL,
    COMPTE_SOURCE_ID VARCHAR2(64) NOT NULL,
    COMPTE_DEST_RIB VARCHAR2(34) NOT NULL,
    NOM_BENEFICIAIRE VARCHAR2(150) NOT NULL,
    MONTANT NUMBER(15, 3) NOT NULL,
    MOTIF VARCHAR2(255),
    STATUT VARCHAR2(30) DEFAULT 'EXECUTE' NOT NULL,
    DATE_EXECUTION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    REFERENCE_BNA VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (ID),
    CONSTRAINT UQ_TRANS_REF UNIQUE (REFERENCE_BNA),
    CONSTRAINT FK_TRANS_COMPTE FOREIGN KEY (COMPTE_SOURCE_ID) REFERENCES BNA_COMPTES(ID)
);

-- 4. TABLE DU JOURNAL D'AUDIT SYSTÈME
CREATE TABLE BNA_JOURNAL_AUDIT (
    ID VARCHAR2(64) NOT NULL,
    DATE_HEURE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UTILISATEUR_ID VARCHAR2(50) NOT NULL,
    ACTION VARCHAR2(100) NOT NULL,
    ADRESSE_IP VARCHAR2(50) DEFAULT '197.0.24.18 (BNA Gateway TLS)',
    STATUT VARCHAR2(20) NOT NULL,
    DETAILS CLOB,
    CONSTRAINT PK_JOURNAL_AUDIT PRIMARY KEY (ID),
    CONSTRAINT CK_AUDIT_STATUT CHECK (STATUT IN ('SUCCES', 'ECHEC', 'ALERTE'))
);

CREATE INDEX IDX_BNA_AUDIT_USER ON BNA_JOURNAL_AUDIT (UTILISATEUR_ID);
CREATE INDEX IDX_BNA_AUDIT_DATE ON BNA_JOURNAL_AUDIT (DATE_HEURE);

